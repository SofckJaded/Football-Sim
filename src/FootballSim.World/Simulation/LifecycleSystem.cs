    /// <summary>
    /// Copies an amateur contract template onto a player's (get-only) contract object. <see cref="WorldPlayer"/>
    /// owns one contract instance for its lifetime, so lifecycle changes mutate that instance rather than
    /// replacing it.
    /// </summary>
    private static void ResetContract(PlayerContract target, PlayerContract template)
    {
        target.SignedSeason = template.SignedSeason;
        target.EndSeason = template.EndSeason;
        target.WeeklyWage = template.WeeklyWage;
        target.IsOnLoan = template.IsOnLoan;
        target.ParentClubId = template.ParentClubId;
        target.LoanEndSeason = template.LoanEndSeason;
    }

    /// <summary>
    /// Gives an intake player a simple amateur deal: zero wage, two or three seasons. The finance system
    /// prices it later; the lifecycle only guarantees the player is contracted to his academy club.
    /// </summary>
    private static void SetYouthContract(PlayerContract contract, int season, WorldRng rng)
    {
        int seasons = MinimumIntakeContractSeasons +
            rng.NextInt(0, MaximumIntakeContractSeasons - MinimumIntakeContractSeasons + 1);

        contract.SignedSeason = season;
        contract.EndSeason = season + seasons - 1;
        contract.WeeklyWage = 0;
        contract.IsOnLoan = false;
        contract.ParentClubId = ClubId.None;
        contract.LoanEndSeason = 0;
    }

