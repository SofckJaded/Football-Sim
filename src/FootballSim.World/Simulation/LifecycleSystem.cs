/// <summary>Outcome of one weekly injury-recovery tick.</summary>
/// <param name="Recovered">Injured players who became fit again during this tick.</param>
/// <param name="StillInjured">Players who were injured at the start of the tick and still are afterwards.</param>
public sealed record InjuryTickResult(int Recovered, int StillInjured);

/// <summary>One player who retired in the off-season rollover.</summary>
/// <param name="PlayerId">The retired player.</param>
/// <param name="ClubId">The club he retired from, or <see cref="ClubId.None"/> when he was a free agent.</param>
/// <param name="Age">His age in the season he retired (after the annual aging step).</param>
public sealed record RetirementRecord(PlayerId PlayerId, ClubId ClubId, int Age);

/// <summary>One player created by a club's annual youth intake.</summary>
/// <param name="PlayerId">The newly generated player.</param>
/// <param name="ClubId">The club that signed him.</param>
/// <param name="Age">His starting age (16 or 17).</param>
public sealed record YouthIntakeRecord(PlayerId PlayerId, ClubId ClubId, int Age);

/// <summary>
/// What one off-season rollover produced: the retirement/youth-intake ledgers, how many players were aged and
/// the resulting active population (plan §5.2, stage W3).
/// </summary>
public sealed class LifecycleRolloverResult
{
    /// <summary>Number of players that retired this off-season.</summary>
    public int Retirements { get; init; }

    /// <summary>Number of players generated by youth intakes this off-season.</summary>
    public int YouthIntakes { get; init; }

    /// <summary>Number of active players that were aged by one year.</summary>
    public int PlayersAged { get; init; }

    /// <summary>Active population after every retirement and intake has been applied.</summary>
    public int ActivePopulation { get; init; }

    /// <summary>Every retirement, in the registry order the rollover processed them.</summary>
    public IReadOnlyList<RetirementRecord> Retired { get; init; } = Array.Empty<RetirementRecord>();

    /// <summary>Every youth intake, in club order then intake order.</summary>
    public IReadOnlyList<YouthIntakeRecord> Intakes { get; init; } = Array.Empty<YouthIntakeRecord>();
}

/// <summary>
/// The player-lifecycle system of the living world (plan §5.2, stage W3): weekly injury recovery, annual
/// aging, retirements and youth intake regens.
///
/// <para><b>Injury recovery.</b> The season runner already ticks every injury down one base week per week
/// (<see cref="WorldSeasonRunner"/>'s player tick). <see cref="AdvanceInjuries"/> is the club-medical layer
/// on top of that base countdown: once per week, each injured player has a chance to recover one additional
/// week, and a better <see cref="ClubFacilities.MedicalQuality01"/> makes that chance larger. The base
/// countdown is therefore always guaranteed; medical quality only ever accelerates it.</para>
///
/// <para><b>Off-season order.</b> <see cref="ProcessOffSeason"/> ages every active player first, then resolves
/// retirements (age-driven, then the clubless-viability pass), then runs the youth intake and finally
/// balances the population into the documented band. It is meant to run at season end after
/// promotion/relegation and before the contract and schedule systems, so a retiring player's contract does
/// not need managing and the new youth are present for squad building.</para>
///
/// <para><b>Determinism.</b> Every collection is iterated in registry/club-id order and every random draw
/// comes from the supplied <see cref="WorldRng"/> in a fixed order: retirement rolls in registry order after
/// the aging pass, then two intake-count rolls per club in club order, then per-intake age/name/contract
/// draws. Player attribute seeds are forks of <see cref="WorldRng.Seed"/> (not the advancing state), so name
/// collisions can never change what a generated player looks like.</para>
/// </summary>
public static class LifecycleSystem
{
    // ---------------------------------------------------------------------------------------------
    // Population band (plan §5.2: the world must self-sustain over 20+ seasons).
    // ---------------------------------------------------------------------------------------------

    /// <summary>Lowest active population the intake balancing accepts (plan §5.2 band, stage W3 gate).</summary>
    public const int MinimumActivePopulation = 2450;

    /// <summary>
    /// Population the balancing aims for when the world has fallen below
    /// <see cref="MinimumActivePopulation"/>: extra intakes keep being added until the projected population
    /// reaches this target (or every club hits its balancing cap).
    /// </summary>
    public const int TargetActivePopulation = 2600;

    /// <summary>Highest active population the intake balancing accepts; intakes above it are skipped.</summary>
    public const int MaximumActivePopulation = 2750;

    // ---------------------------------------------------------------------------------------------
    // Injury recovery constants.
    // ---------------------------------------------------------------------------------------------

    /// <summary>Base chance that an injured player recovers one additional week in a week.</summary>
    private const float BaseMedicalRecoveryChance = 0.10f;

    /// <summary>How much a club's medical quality adds to the additional-recovery chance.</summary>
    private const float MedicalQualityRecoveryWeight = 0.35f;

    // ---------------------------------------------------------------------------------------------
    // Retirement constants.
    // ---------------------------------------------------------------------------------------------

    /// <summary>Age at which retirement is certain (plan §5.2: guaranteed by 40).</summary>
    private const int ForcedRetirementAge = 40;

    /// <summary>First age at which the age-driven retirement probability applies.</summary>
    private const int RetirementAgeFloor = 33;

    /// <summary>Per-year increase of the retirement probability from age 33 upwards.</summary>
    private const float RetirementProbabilityPerYear = 0.055f;

    /// <summary>Cap of the age-driven retirement probability (before the situational bonuses).</summary>
    private const float MaximumAgeRetirementProbability = 0.85f;

    /// <summary>Extra retirement probability for a player whose mean current attribute is poor.</summary>
    private const float WeakPlayerRetirementBonus = 0.12f;

    /// <summary>Mean current attribute below which a player counts as a weak survivor.</summary>
    private const float WeakPlayerMeanCurrentThreshold = 32f;

    /// <summary>Extra retirement probability for a player without a club.</summary>
    private const float FreeAgentRetirementBonus = 0.05f;

    // ---------------------------------------------------------------------------------------------
    // Youth intake constants.
    // ---------------------------------------------------------------------------------------------

    /// <summary>Minimum intake per club before the population balancing pass.</summary>
    private const int MinimumRolledIntakesPerClub = 1;

    /// <summary>Maximum intake per club from the quality rolls (the balancing pass may add more).</summary>
    private const int MaximumRolledIntakesPerClub = 3;

    /// <summary>Most extra intakes the population-balancing pass may add to one club.</summary>
    private const int MaximumBalancingIntakesPerClub = 3;

    /// <summary>Base chance of a second (or third) intake before the club's youth quality is read.</summary>
    private const float SecondIntakeBaseChance = 0.20f;
    private const float ThirdIntakeBaseChance = 0.05f;

    /// <summary>How much a club's youth quality adds to the second/third intake chances.</summary>
    private const float SecondIntakeYouthQualityWeight = 0.35f;
    private const float ThirdIntakeYouthQualityWeight = 0.15f;

    /// <summary>Youngest/oldest intake age.</summary>
    private const int MinimumIntakeAge = 16;
    private const int MaximumIntakeAge = 17;

    /// <summary>Ordinal base of the per-intake player-generation forks (kept clear of slot ordinals).</summary>
    private const ulong IntakeSeedOrdinalBase = 1000UL;

    /// <summary>Multiplier that folds the club id into the player-generation fork ordinal.</summary>
    private const ulong IntakeSeedClubMultiplier = 31UL;

    /// <summary>Random full-name pairs tried before the roman-numeral uniqueness fallback.</summary>
    private const int MaximumNameAttempts = 25;

    /// <summary>Vocabulary size of <see cref="RosterGroup"/>; used by the deterministic group cycle.</summary>
    private const int RosterGroupCount = 4;

    /// <summary>Contract length range for an intake player (the finance system prices it later).</summary>
    private const int MinimumIntakeContractSeasons = 2;
    private const int MaximumIntakeContractSeasons = 3;

    // ---------------------------------------------------------------------------------------------
    // Population.
    // ---------------------------------------------------------------------------------------------

    /// <summary>Number of players in the registry that have not retired.</summary>
    /// <param name="world">The world to count.</param>
    /// <exception cref="ArgumentNullException"><paramref name="world"/> is null.</exception>
    public static int CountActivePlayers(WorldState world)
    {
        ArgumentNullException.ThrowIfNull(world);

        int active = 0;
        foreach (WorldPlayer player in world.Players.All)
        {
            if (!player.IsRetired) active++;
        }

        return active;
    }

    // ---------------------------------------------------------------------------------------------
    // Weekly injury recovery.
    // ---------------------------------------------------------------------------------------------

    /// <summary>
    /// Applies this week's club-medical recovery on top of the season runner's base one-week countdown.
    ///
    /// <para>Every injured player, in registry order, draws once: with probability
    /// <c>0.10 + 0.35 * medicalQuality01</c> he recovers one additional week (never below zero, always through
    /// <see cref="InjuryState.AdvanceWeek"/>). A player without a club has no medical department and uses the
    /// 0.10 base chance. The runner's own weekly tick remains the guaranteed base recovery; this call only
    /// ever accelerates it, which is why the ecosystem calls both once per week.</para>
    /// </summary>
    /// <param name="world">The world whose injuries tick.</param>
    /// <returns>How many injured players recovered and how many remain injured.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="world"/> is null.</exception>
    public static InjuryTickResult AdvanceInjuries(WorldState world)
    {
        ArgumentNullException.ThrowIfNull(world);

        WorldRng rng = world.Stream(WorldRandomStream.Injuries);
        int recovered = 0;
        int stillInjured = 0;

        foreach (WorldPlayer player in world.Players.All)
        {
            if (!player.Injury.IsInjured) continue;

            float chance = BaseMedicalRecoveryChance +
                MedicalQualityRecoveryWeight * MedicalQualityOf(world, player.ClubId);
            if (rng.NextFloat() < chance) player.Injury.AdvanceWeek();

            if (player.Injury.IsInjured) stillInjured++;
            else recovered++;
        }

        return new InjuryTickResult(recovered, stillInjured);
    }

    /// <summary>
    /// Starts an injury on a fit player. Severe injuries (and worse) also apply the growth engine's permanent
    /// ceiling damage exactly once: the injury's own ledger makes a repeat call for the same injury a no-op.
    /// </summary>
    /// <param name="world">The world the player belongs to (accepted so every lifecycle mutation routes through the world).</param>
    /// <param name="player">The player to injure; he must be fit and active.</param>
    /// <param name="kind">Injury kind (not <see cref="InjuryKind.None"/>).</param>
    /// <param name="severity">Injury severity (not <see cref="InjurySeverity.None"/>).</param>
    /// <param name="weeksOut">Weeks the player misses (positive).</param>
    /// <param name="rng">The injuries random stream (permanent-damage rolls).</param>
    /// <exception cref="ArgumentNullException">A reference argument is null.</exception>
    /// <exception cref="InvalidOperationException">The player is already injured or has retired.</exception>
    /// <exception cref="ArgumentOutOfRangeException">The injury kind/severity/weeks are invalid.</exception>
    public static void ApplyInjury(
        WorldState world,
        WorldPlayer player,
        InjuryKind kind,
        InjurySeverity severity,
        int weeksOut,
        WorldRng rng)
    {
        ArgumentNullException.ThrowIfNull(world);
        ArgumentNullException.ThrowIfNull(player);
        ArgumentNullException.ThrowIfNull(rng);

        if (player.IsRetired)
        {
            throw new InvalidOperationException($"Player {player.Id} has retired and cannot be injured.");
        }

        if (player.Injury.IsInjured)
        {
            throw new InvalidOperationException(
                $"Player {player.Id} is already injured ({player.Injury.Kind}, " +
                $"{player.Injury.WeeksOutRemaining} weeks left).");
        }

        // Begin() performs the range validation (kind/severity/weeksOut) and resets the damage ledger.
        player.Injury.Begin(kind, severity, weeksOut);

        // Severe, season-ending and career-threatening injuries leave permanent physical damage. The growth
        // engine guards repeat application through InjuryState.PermanentDamageApplied, so this is one shot.
        if (severity >= InjurySeverity.Severe)
        {
            GrowthEngine.ApplyPermanentInjuryDamage(player, kind, rng);
        }
    }

    // ---------------------------------------------------------------------------------------------
    // Retirement.
    // ---------------------------------------------------------------------------------------------

    /// <summary>
    /// Whether an active player retires this off-season. Age 40 and above always retires; below 33 the answer
    /// is no; from 33 the chance is <c>clamp(0.055 * (Age - 32), 0, 0.85)</c>, plus 0.12 for a player whose
    /// mean current attribute is below 32 and 0.05 for a player without a club.
    ///
    /// <para>Draw order: the forced-retirement and under-33 paths consume no randomness; every other call
    /// consumes exactly one <see cref="WorldRng.NextFloat"/> draw.</para>
    /// </summary>
    /// <param name="player">The player to test (his age must already be the post-aging age).</param>
    /// <param name="rng">The regens random stream.</param>
    /// <exception cref="ArgumentNullException"><paramref name="player"/> or <paramref name="rng"/> is null.</exception>
    public static bool ShouldRetire(WorldPlayer player, WorldRng rng)
    {
        ArgumentNullException.ThrowIfNull(player);
        ArgumentNullException.ThrowIfNull(rng);

        if (player.Age >= ForcedRetirementAge) return true;
        if (player.Age < RetirementAgeFloor) return false;

        float probability = Math.Clamp(
            RetirementProbabilityPerYear * (player.Age - (RetirementAgeFloor - 1)),
            0f,
            MaximumAgeRetirementProbability);

        if (player.Attributes.MeanCurrent() < WeakPlayerMeanCurrentThreshold)
        {
            probability += WeakPlayerRetirementBonus;
        }

        if (!player.ClubId.IsValid) probability += FreeAgentRetirementBonus;

        return rng.NextFloat() < probability;
    }

    // ---------------------------------------------------------------------------------------------
    // Off-season rollover.
    // ---------------------------------------------------------------------------------------------

    /// <summary>
    /// Runs the annual player lifecycle: age every active player by one year, retire the players
    /// <see cref="ShouldRetire"/> accepts (and every player who is still clubless after a full season),
    /// run every club's youth intake and balance the active population
    /// into <see cref="MinimumActivePopulation"/>..<see cref="MaximumActivePopulation"/>.
    ///
    /// <para><b>Order (part of the contract).</b></para>
    /// <list type="number">
    /// <item>Aging: every non-retired player's age advances by one, in registry order.</item>
    /// <item>Retirements: every still-active player is tested in registry order. A retirement removes the
    /// player from his club squad, clears his injury/suspension/contract and appends a
    /// <see cref="TransferKind.Retirement"/> entry to the transfer log; he stays in the registry with
    /// <see cref="WorldPlayer.IsRetired"/> set so history and ids keep resolving.</item>
    /// <item>Clubless viability: a still-active player with no club retires (the transfer market has had
    /// both windows, and a clubless player has no route back into the registered game in v1). This consumes
    /// no randomness and keeps the free-agent population from growing without bound.</item>
    /// <item>Youth intake: each club rolls one guaranteed intake plus a second/third chance driven by its
    /// <see cref="ClubFacilities.YouthQuality01"/>; the population is then balanced (extra intakes when below
    /// the minimum, skipped intakes when above the maximum) and every accepted intake is generated as a
    /// 16/17-year-old NPC for the club's positional shortfall, with a unique name and an amateur contract.</item>
    /// </list>
    ///
    /// <para><b>Randomness.</b> The draws are: two intake-count rolls per club (in club order), then per
    /// accepted intake one age roll, the name-pair draws (with uniqueness retries) and one contract-length
    /// roll. Retirement rolls happen before them, in registry order. All draws come from
    /// <paramref name="rng"/>, so two identical worlds with the same generator seed roll the same season.</para>
    /// </summary>
    /// <param name="world">The world to roll over; it must be at season end.</param>
    /// <param name="rng">The regens random stream (the ecosystem passes the world's regens stream).</param>
    /// <returns>The retirement/intake ledgers and the resolved active population.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="world"/> or <paramref name="rng"/> is null.</exception>
    public static LifecycleRolloverResult ProcessOffSeason(WorldState world, WorldRng rng)
    {
        ArgumentNullException.ThrowIfNull(world);
        ArgumentNullException.ThrowIfNull(rng);

        int season = world.Season;
        int week = world.Week;

        // 1. Age every active player by one year.
        int playersAged = 0;
        foreach (WorldPlayer player in world.Players.All)
        {
            if (player.IsRetired) continue;
            player.Age++;
            playersAged++;
        }

        // 2. Retirements, in registry order.
        var retired = new List<RetirementRecord>();
        foreach (WorldPlayer player in world.Players.All)
        {
            if (player.IsRetired) continue;
            if (!ShouldRetire(player, rng)) continue;

            RetirePlayer(world, player, season, week, retired);
        }

        // 2b. Off-season viability. A player who reaches the end of a season without a club has been
        // through both transfer windows and the market has not signed him: the free-agent rules only take
        // players up to age 30 with a usable area score, so in v1 the rest have no route back into football.
        // Ending their careers here (the plan's "career-ending drop below Tier 6 viability") is what keeps
        // the clubless population bounded; letting it grow would leave the intake balancing counting
        // unregistered players and starve the registered squads that actually need to field a team.
        // No randomness is consumed, so the documented draw order for the retention rolls is unchanged.
        foreach (WorldPlayer player in world.Players.All)
        {
            if (player.IsRetired) continue;
            if (player.ClubId.IsValid) continue;

            RetirePlayer(world, player, season, week, retired);
        }

        // 3. Youth intake. Plan the per-club counts first (rng rolls in club order), balance the population,
        //    then generate the players.
        IReadOnlyList<WorldClub> clubs = world.Clubs.All;
        int clubCount = clubs.Count;
        var plannedIntakes = new int[clubCount];
        for (int clubIndex = 0; clubIndex < clubCount; clubIndex++)
        {
            WorldClub club = clubs[clubIndex];
            float youthQuality = club.Facilities.YouthQuality01;

            int count = MinimumRolledIntakesPerClub;
            if (rng.NextFloat() < SecondIntakeBaseChance + SecondIntakeYouthQualityWeight * youthQuality)
            {
                count++;
            }

            if (rng.NextFloat() < ThirdIntakeBaseChance + ThirdIntakeYouthQualityWeight * youthQuality)
            {
                count++;
            }

            plannedIntakes[clubIndex] = count;
        }

        int activeAfterRetirements = CountActivePlayers(world);
        AddIntakesToReachMinimum(plannedIntakes, activeAfterRetirements);
        TrimIntakesToMaximum(plannedIntakes, activeAfterRetirements);

        var intakes = new List<YouthIntakeRecord>();
        HashSet<string> usedNames = BuildUsedNameSet(world);
        NamePools names = world.Pack.Names;

        for (int clubIndex = 0; clubIndex < clubCount; clubIndex++)
        {
            int intakeCount = plannedIntakes[clubIndex];
            if (intakeCount == 0) continue;

            WorldClub club = clubs[clubIndex];
            for (int intakeIndex = 0; intakeIndex < intakeCount; intakeIndex++)
            {
                // The academy fills the area the squad lacks most; with no shortfall the intake cycles
                // deterministically through the four broad areas.
                RosterGroup group = RosterAnalyser.FindShortfall(world, club)
                    ?? (RosterGroup)((club.Id.Value + intakeIndex) % RosterGroupCount);
                TacticalRole role = MapIntakeRole(group, intakeIndex);
                int age = MinimumIntakeAge + rng.NextInt(0, MaximumIntakeAge - MinimumIntakeAge + 1);

                // A fork of the generator's SEED (not its state), so name retries cannot move attributes.
                ulong playerSeed = rng
                    .Fork((ulong)club.Id.Value * IntakeSeedClubMultiplier +
                        (ulong)intakeIndex + IntakeSeedOrdinalBase)
                    .Seed;

                PickUniqueName(rng, names, usedNames, out string firstName, out string lastName);
                PlayerId playerId = world.AllocatePlayerId();

                WorldPlayer player = PlayerGenerator.GenerateNpcForTier(
                    playerSeed, club.Tier, age, role, playerId, firstName, lastName);
                player.ClubId = club.Id;
                player.TrainingFocus = FocusForRole(role);
                SetYouthContract(player.Contract, season, rng);

                club.AddPlayer(player.Id);
                club.SetManagerTrust(player.Id, 0.5f);
                world.Players.Add(player);

                // The transfer log is the world's audit trail: a youth intake is a move from no club to his
                // academy club, so the soak test's intake volume is measurable without a second ledger.
                world.RecordTransfer(new TransferRecord(
                    season, week, playerId, ClubId.None, club.Id, TransferKind.YouthIntake, 0));
                intakes.Add(new YouthIntakeRecord(playerId, club.Id, age));
            }
        }

        return new LifecycleRolloverResult
        {
            Retirements = retired.Count,
            YouthIntakes = intakes.Count,
            PlayersAged = playersAged,
            ActivePopulation = CountActivePlayers(world),
            Retired = retired.AsReadOnly(),
            Intakes = intakes.AsReadOnly()
        };
    }

    // ---------------------------------------------------------------------------------------------
    // Population balancing.
    // ---------------------------------------------------------------------------------------------

    /// <summary>
    /// Ends one player's career: removes him from his squad, clears every availability flag, gives him the
    /// default amateur terms (so nothing keeps paying him) and records the retirement on the world's ledger.
    /// Shared by the age-driven retirement pass and the clubless-viability pass so both produce identical
    /// ledgers.
    /// </summary>
    private static void RetirePlayer(
        WorldState world, WorldPlayer player, int season, int week, List<RetirementRecord> retired)
    {
        ClubId oldClubId = player.ClubId;
        int retirementAge = player.Age;

        if (oldClubId.IsValid && world.Clubs.TryGet(oldClubId, out WorldClub? oldClub) && oldClub is not null)
        {
            oldClub.RemovePlayer(player.Id);
        }

        player.IsRetired = true;
        player.ClubId = ClubId.None;
        player.Injury.Clear();
        player.SuspensionWeeksRemaining = 0;
        ResetContract(player.Contract, PlayerContract.Amateur(season));

        world.RecordTransfer(new TransferRecord(
            season, week, player.Id, oldClubId, ClubId.None, TransferKind.Retirement, 0));
        retired.Add(new RetirementRecord(player.Id, oldClubId, retirementAge));
    }


    /// <summary>
    /// Adds extra youth to the clubs with the fewest intakes (ties by club order) until the projected
    /// population reaches <see cref="TargetActivePopulation"/>, capped at
    /// <see cref="MaximumBalancingIntakesPerClub"/> extra players per club. Only runs when the projected
    /// population would end below <see cref="MinimumActivePopulation"/>.
    /// </summary>
    private static void AddIntakesToReachMinimum(int[] plannedIntakes, int activeAfterRetirements)
    {
        int projected = activeAfterRetirements;
        for (int clubIndex = 0; clubIndex < plannedIntakes.Length; clubIndex++)
        {
            projected += plannedIntakes[clubIndex];
        }

        if (projected >= MinimumActivePopulation) return;

        int clubCount = plannedIntakes.Length;
        var added = new int[clubCount];
        while (projected < TargetActivePopulation)
        {
            // Fewest current intakes wins; the ascending scan makes ties break on club-id order.
            int best = -1;
            int bestIntakes = int.MaxValue;
            for (int clubIndex = 0; clubIndex < clubCount; clubIndex++)
            {
                int total = plannedIntakes[clubIndex] + added[clubIndex];
                if (added[clubIndex] >= MaximumBalancingIntakesPerClub) continue;
                if (total < bestIntakes)
                {
                    bestIntakes = total;
                    best = clubIndex;
                }
            }

            if (best < 0) return; // every club is at the balancing cap: the world stays below the target.
            added[best]++;
            projected++;
        }

        for (int clubIndex = 0; clubIndex < clubCount; clubIndex++)
        {
            plannedIntakes[clubIndex] += added[clubIndex];
        }
    }

    /// <summary>
    /// Skips youth intakes when the projected population would exceed
    /// <see cref="MaximumActivePopulation"/>. Every club keeps one intake while the budget allows it; the
    /// surplus extras are dropped evenly across the clubs (a deterministic "skip every k-th" selection), and
    /// when even one intake per club is too many, whole clubs' intakes are skipped evenly over club order.
    /// </summary>
    private static void TrimIntakesToMaximum(int[] plannedIntakes, int activeAfterRetirements)
    {
        int plannedTotal = 0;
        for (int clubIndex = 0; clubIndex < plannedIntakes.Length; clubIndex++)
        {
            plannedTotal += plannedIntakes[clubIndex];
        }

        int budget = MaximumActivePopulation - activeAfterRetirements;
        if (activeAfterRetirements + plannedTotal <= MaximumActivePopulation) return;

        int clubCount = plannedIntakes.Length;
        if (budget <= 0)
        {
            Array.Clear(plannedIntakes);
            return;
        }

        if (budget < clubCount)
        {
            // Not even one intake per club fits: keep the budget clubs spread evenly across club order.
            for (int clubIndex = 0; clubIndex < clubCount; clubIndex++)
            {
                long previous = (long)clubIndex * budget / clubCount;
                long current = (long)(clubIndex + 1) * budget / clubCount;
                plannedIntakes[clubIndex] = current != previous ? 1 : 0;
            }

            return;
        }

        // Every club keeps its guaranteed intake; the extras are trimmed evenly.
        int extraBudget = budget - clubCount;
        var extras = new int[clubCount];
        int extraCount = 0;
        for (int clubIndex = 0; clubIndex < clubCount; clubIndex++)
        {
            extras[clubIndex] = plannedIntakes[clubIndex] - MinimumRolledIntakesPerClub;
            extraCount += extras[clubIndex];
        }

        if (extras.Length == 0 || extraCount <= extraBudget) return;

        var keptExtras = new int[clubCount];
        int extraClubIndex = 0;
        int usedInClub = 0;
        for (int extraIndex = 0; extraIndex < extraCount; extraIndex++)
        {
            while (usedInClub >= extras[extraClubIndex])
            {
                extraClubIndex++;
                usedInClub = 0;
            }

            // Bresenham-style even acceptance: exactly `extraBudget` extras survive the trim.
            long previous = (long)extraIndex * extraBudget / extraCount;
            long current = (long)(extraIndex + 1) * extraBudget / extraCount;
            if (current != previous) keptExtras[extraClubIndex]++;

            usedInClub++;
        }

        for (int clubIndex = 0; clubIndex < clubCount; clubIndex++)
        {
            plannedIntakes[clubIndex] = MinimumRolledIntakesPerClub + keptExtras[clubIndex];
        }
    }

    // ---------------------------------------------------------------------------------------------
    // Youth-intake helpers.
    // ---------------------------------------------------------------------------------------------

    /// <summary>Maps a broad roster group to the generator's tactical-role vocabulary.</summary>
    private static TacticalRole MapIntakeRole(RosterGroup group, int intakeIndex) => group switch
    {
        RosterGroup.Goalkeeper => TacticalRole.Goalkeeper,
        RosterGroup.Defender => (intakeIndex % 3) switch
        {
            0 => TacticalRole.CenterBack,
            1 => TacticalRole.FullBack,
            _ => TacticalRole.DefensiveMidfielder
        },
        RosterGroup.Midfielder => TacticalRole.CentralMidfielder,
        _ => (intakeIndex % 2) == 0 ? TacticalRole.Winger : TacticalRole.Striker
    };

    /// <summary>The weekly training focus an intake player starts on, from the role he was generated for.</summary>
    private static TrainingFocus FocusForRole(TacticalRole role) => role switch
    {
        TacticalRole.Goalkeeper => TrainingFocus.Goalkeeping,
        TacticalRole.CenterBack or TacticalRole.FullBack or TacticalRole.DefensiveMidfielder =>
            TrainingFocus.DefendingAndPositioning,
        TacticalRole.CentralMidfielder => TrainingFocus.PassingAndVision,
        TacticalRole.Winger => TrainingFocus.BallControlAndDribbling,
        TacticalRole.Striker => TrainingFocus.FinishingAndShooting,
        _ => TrainingFocus.Balanced
    };

    /// <summary>Case-insensitive set of every player's full name, so new intakes cannot duplicate a name.</summary>
    private static HashSet<string> BuildUsedNameSet(WorldState world)
    {
        var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (WorldPlayer player in world.Players.All)
        {
            used.Add(player.DisplayName);
        }

        return used;
    }

    /// <summary>
    /// Picks a full name unique across the world: up to <see cref="MaximumNameAttempts"/> name-pair draws,
    /// then the last drawn pair with a roman-numeral suffix ("II", "III", ...). Deterministic and total — it
    /// never fails on a finite name pool.
    /// </summary>
    private static void PickUniqueName(
        WorldRng rng, NamePools names, HashSet<string> usedNames, out string firstName, out string lastName)
    {
        firstName = string.Empty;
        lastName = string.Empty;

        for (int attempt = 0; attempt < MaximumNameAttempts; attempt++)
        {
            firstName = names.FirstNames[rng.NextIndex(names.FirstNames.Count)];
            lastName = names.LastNames[rng.NextIndex(names.LastNames.Count)];
            if (usedNames.Add(names.ComposeName(firstName, lastName))) return;
        }

        for (int suffix = 2; suffix <= 3999; suffix++)
        {
            string candidate = $"{names.ComposeName(firstName, lastName)} {ToRomanNumeral(suffix)}";
            if (usedNames.Add(candidate)) return;
        }

        throw new InvalidOperationException("Could not find a unique youth-intake name in the data pack.");
    }

    /// <summary>Formats a value 1..3999 as a roman numeral (used for the intake name fallback).</summary>
    private static string ToRomanNumeral(int value)
    {
        if (value is < 1 or > 3999)
        {
            throw new ArgumentOutOfRangeException(nameof(value), value, "Roman numerals cover 1..3999.");
        }

        int[] numbers = { 1000, 900, 500, 400, 100, 90, 50, 40, 10, 9, 5, 4, 1 };
        string[] symbols = { "M", "CM", "D", "CD", "C", "XC", "L", "XL", "X", "IX", "V", "IV", "I" };

        var builder = new StringBuilder(8);
        for (int index = 0; index < numbers.Length; index++)
        {
            while (value >= numbers[index])
            {
                builder.Append(symbols[index]);
                value -= numbers[index];
            }
        }

        return builder.ToString();
    }

