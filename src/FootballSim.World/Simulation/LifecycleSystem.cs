    /// <summary>Medical quality of the player's club, or 0 when he has no club.</summary>
    private static float MedicalQualityOf(WorldState world, ClubId clubId)
    {
        if (!clubId.IsValid) return 0f;
        return world.Clubs.TryGet(clubId, out WorldClub? club) && club is not null
            ? club.Facilities.MedicalQuality01
            : 0f;
    }
